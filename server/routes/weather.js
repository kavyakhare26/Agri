// ── Rule-based Pest & Weather Hazard Evaluation ──────────────────────────────
const generatePestAlerts = async (weatherData, userId) => {
  const { current, location } = weatherData;
  const { humidity, temp, description, rainProbability } = current;
  const candidateRisks = [];

  // Rule 1: High Humidity (>80%) -> Fungal disease risk
  if (humidity > 80) {
    candidateRisks.push({
      title: 'High Fungal Disease Risk',
      description: `Humidity is very high at ${humidity}%. Fungal spores thrive in conditions above 80% RH. Inspect crops for powdery mildew and blast, apply preventive bio-fungicide, and improve field drainage.`,
      severity: 'high',
      type: 'fungal',
      region: location,
      triggerCondition: `humidity (${humidity}%) > 80%`,
      autoGenerated: true,
      affectedCrops: ['Rice', 'Wheat', 'Tomato', 'Grapes', 'Potato'],
      postedBy: userId,
      isActive: true,
    });
  }

  // Rule 2: High Temperature (>38°C) -> Heat stress & aphids
  if (temp > 38) {
    candidateRisks.push({
      title: 'Extreme Heat Stress & Pest Warning',
      description: `Current temperature is ${temp}°C (above 38°C threshold). Severe risk of moisture stress and aphid infestation. Irrigate during evening/early morning hours and use light mulching.`,
      severity: 'high',
      type: 'insect',
      region: location,
      triggerCondition: `temp (${temp}°C) > 38°C`,
      autoGenerated: true,
      affectedCrops: ['Cotton', 'Maize', 'Soybean', 'Vegetables'],
      postedBy: userId,
      isActive: true,
    });
  }

  // Rule 3: Heavy Rain or Rain Probability > 70% -> Waterlogging & Root Rot Risk
  if ((rainProbability && rainProbability >= 70) || /rain|shower|storm/i.test(description || '')) {
    candidateRisks.push({
      title: 'Waterlogging & Root Rot Hazard',
      description: `Heavy precipitation expected (${description || 'high rain probability'}). Risk of waterlogging leading to root rot (Rhizoctonia/Phytophthora). Ensure drainage trenches are unclogged.`,
      severity: 'medium',
      type: 'flood',
      region: location,
      triggerCondition: `rain / rainProb >= 70%`,
      autoGenerated: true,
      affectedCrops: ['Pulses', 'Chilli', 'Groundnut', 'Cotton'],
      postedBy: userId,
      isActive: true,
    });
  }

  // Rule 4: Dry conditions (<30% humidity) -> Spider mites & drought
  if (humidity < 30) {
    candidateRisks.push({
      title: 'Low Humidity & Spider Mite Warning',
      description: `Dry atmospheric conditions with humidity at ${humidity}%. Spider mites proliferate in low moisture. Check undersides of leaves and maintain micro-irrigation.`,
      severity: 'medium',
      type: 'drought',
      region: location,
      triggerCondition: `humidity (${humidity}%) < 30%`,
      autoGenerated: true,
      affectedCrops: ['Cotton', 'Okra', 'Brinjal'],
      postedBy: userId,
      isActive: true,
    });
  }

  const createdAlerts = [];
  for (const risk of candidateRisks) {
    // Avoid duplicate alerts for same title & region in the last 2 hours
    const recent = await PestAlert.findOne({
      title: risk.title,
      region: risk.region,
      createdAt: { $gte: new Date(Date.now() - 2 * 60 * 60 * 1000) },
    });
    if (!recent) {
      const saved = await PestAlert.create(risk);
      createdAlerts.push(saved);
    } else {
      createdAlerts.push(recent);
    }
  }

  return createdAlerts;
};

// ─── GET /api/weather?location=CityName ─────────────────────────────────────
// 30-minute caching in MongoDB; OWM key support; mock fallback; auto pest alert generation
router.get('/', async (req, res, next) => {
  try {
    const location = (req.query.location || 'Pune, Maharashtra').trim();
    const CACHE_TTL_MS = 30 * 60 * 1000; // 30 minutes

    // 1. Check DB Cache
    const existing = await WeatherData.findOne({
      location: { $regex: new RegExp(`^${location}$`, 'i') },
    });

    if (existing && existing.fetchedAt && (Date.now() - new Date(existing.fetchedAt).getTime() < CACHE_TTL_MS)) {
      const pestAlerts = await generatePestAlerts(existing, req.user._id);
      return res.json({
        success: true,
        message: 'Weather data retrieved (cached)',
        cached: true,
        data: existing,
        pestAlerts,
      });
    }

    // 2. Fetch fresh weather data: OpenWeatherMap or Mock Fallback
    const apiKey = process.env.OPENWEATHER_API_KEY || process.env.OWM_API_KEY;
    let weatherPayload = null;

    if (apiKey && apiKey.length > 8 && apiKey !== 'your_openweathermap_api_key_here') {
      try {
        const [currentRes, forecastRes] = await Promise.all([
          axios.get(`https://api.openweathermap.org/data/2.5/weather?q=${encodeURIComponent(location)}&appid=${apiKey}&units=metric`),
          axios.get(`https://api.openweathermap.org/data/2.5/forecast?q=${encodeURIComponent(location)}&appid=${apiKey}&units=metric`),
        ]);

        const days = {};
        forecastRes.data.list.forEach((item) => {
          const date = item.dt_txt.split(' ')[0];
          if (!days[date] || item.dt_txt.includes('12:00:00')) {
            days[date] = {
              date: new Date(item.dt * 1000),
              tempMin: item.main.temp_min,
              tempMax: item.main.temp_max,
              humidity: item.main.humidity,
              description: item.weather[0].description,
              icon: item.weather[0].icon,
              rainProbability: Math.round((item.pop || 0) * 100),
            };
          }
        });

        weatherPayload = {
          location,
          lat: currentRes.data.coord?.lat,
          lng: currentRes.data.coord?.lon,
          current: {
            temp: currentRes.data.main.temp,
            feelsLike: currentRes.data.main.feels_like,
            humidity: currentRes.data.main.humidity,
            windSpeed: currentRes.data.wind.speed,
            description: currentRes.data.weather[0].description,
            icon: currentRes.data.weather[0].icon,
            visibility: currentRes.data.visibility,
            rainProbability: currentRes.data.rain ? 80 : 20,
          },
          forecast: Object.values(days).slice(0, 5),
        };
      } catch (owmErr) {
        console.warn('OWM request failed, falling back to mock weather:', owmErr.message);
        weatherPayload = getMockWeather(location);
      }
    } else {
      weatherPayload = getMockWeather(location);
    }

    // 3. Save / Upsert to Database with fetchedAt timestamp
    const saved = await WeatherData.findOneAndUpdate(
      { location: { $regex: new RegExp(`^${weatherPayload.location}$`, 'i') } },
      { ...weatherPayload, location: weatherPayload.location, fetchedAt: new Date() },
      { upsert: true, new: true, setDefaultsOnInsert: true }
    );

    // 4. Auto-generate pest alerts based on rules
    const pestAlerts = await generatePestAlerts(saved, req.user._id);

    res.json({
      success: true,
      message: 'Weather data retrieved successfully',
      cached: false,
      data: saved,
      pestAlerts,
    });
  } catch (err) {
    next(err);
  }
});

// ─── POST /api/weather/pest-check ────────────────────────────────────────────
// Manual / test trigger: accepts temp, humidity, rainfall, region
router.post(
  '/pest-check',
  [
    body('humidity').isFloat({ min: 0, max: 100 }).withMessage('Humidity must be 0–100'),
    body('temp').isFloat({ min: -10, max: 60 }).withMessage('Temperature must be -10 to 60°C'),
    body('rainfall').optional().isFloat({ min: 0 }),
    body('region').optional().trim(),
  ],
  validate,
  async (req, res, next) => {
    try {
      const { humidity, temp, rainfall, region, affectedCrops } = req.body;
      const risks = [];

      if (humidity > 80) {
        risks.push({
          title: 'High Fungal Disease Risk',
          description: `Humidity is ${humidity}%. Above 80% threshold creates high fungal pressure. Apply preventive fungicide and improve soil drainage.`,
          severity: 'high',
          type: 'fungal',
          triggerCondition: `humidity (${humidity}%) > 80%`,
        });
      }
      if (temp > 38) {
        risks.push({
          title: 'Extreme Heat Stress & Pest Warning',
          description: `Temperature is ${temp}°C (above 38°C). Rapid wilting and aphid risk. Irrigate during cool hours.`,
          severity: 'high',
          type: 'insect',
          triggerCondition: `temp (${temp}°C) > 38°C`,
        });
      }
      if (rainfall > 50 || req.body.rainProbability > 70) {
        risks.push({
          title: 'Waterlogging & Root Rot Hazard',
          description: `Excess rainfall (${rainfall || 'high probability'}mm) creates root asphyxiation and damping-off hazard.`,
          severity: 'medium',
          type: 'flood',
          triggerCondition: `heavy rain / rainfall > 50mm`,
        });
      }
      if (humidity < 30) {
        risks.push({
          title: 'Low Humidity & Spider Mite Warning',
          description: `Low humidity (${humidity}%) accelerates spider mite reproduction. Keep plants hydrated.`,
          severity: 'medium',
          type: 'drought',
          triggerCondition: `humidity (${humidity}%) < 30%`,
        });
      }

      const savedAlerts = [];
      for (const risk of risks) {
        const alert = await PestAlert.create({
          ...risk,
          region: region || 'Selected Region',
          affectedCrops: affectedCrops || ['General Crops'],
          autoGenerated: true,
          postedBy: req.user._id,
          isActive: true,
        });
        savedAlerts.push(alert);
      }

      res.status(201).json({
        success: true,
        message: `${risks.length} pest risk alert(s) evaluated and generated`,
        risksDetected: risks.length,
        data: risks,
        savedAlerts,
      });
    } catch (err) {
      next(err);
    }
  }
);

module.exports = router;
